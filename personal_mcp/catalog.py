"""Instance-local unified tool schemas; upstream declarations stay unchanged."""

import asyncio
import hashlib
import json
from copy import deepcopy

from jsonschema import Draft202012Validator, SchemaError

from coding_tools_mcp.server import TOOL_REGISTRY, tool_definition

from .tool_policy import KNOWN_TOOLS, READ_ONLY_DESCRIPTORS, WORKFLOW_ACTIONS, requires_workflow_write, reviewed_effects
from .tool_presentation import apply_tool_presentation

WORKFLOW = {"type": "string", "pattern": "^wf_[A-Za-z0-9_-]{43}$"}
WORKFLOW_REF = {"type": "string", "pattern": "^wfr_[0-9a-f]{64}$"}
TEXT = {"type": "string", "minLength": 1, "maxLength": 128}

# Errors generated by the unified authorization/validation layer, before an
# upstream handler can construct its own result. Do not fabricate successful
# file/window/command fields merely to satisfy an upstream output schema.
HOST_ERROR_OUTPUT = {
    'type': 'object', 'required': ['ok', 'error'], 'additionalProperties': False,
    'properties': {
        'ok': {'const': False},
        'error': {'type': 'object', 'required': ['code'], 'additionalProperties': False,
                  'properties': {'code': {'type': 'string', 'minLength': 1},
                                 'details': {'type': 'object'},
                                 'next_action': {'type': 'string'},
                                 'outcome': {'const': 'unknown'}}},
    },
}


def validate_catalog_contract(catalog, *, full_control=False):
    """Reject incomplete descriptors, rather than publish guessed safety hints.

This checks shape and the reviewed read/write classification, not platform
approval or proof that every possible tool side effect has been audited.
"""
    try:
        if not isinstance(catalog, dict) or not catalog:
            raise ValueError
        for name, tool in catalog.items():
            if name not in KNOWN_TOOLS or tool.get('name') != name:
                raise ValueError
            description = tool.get('description')
            if not isinstance(description, str) or not description.strip():
                raise ValueError
            title = tool.get('title')
            if not isinstance(title, str) or not title.strip():
                raise ValueError
            hints = tool['annotations']
            if hints.get('title') != title:
                raise ValueError
            if any(type(hints.get(key)) is not bool for key in
                   ('readOnlyHint', 'destructiveHint', 'openWorldHint')):
                raise ValueError
            if 'idempotentHint' in hints and type(hints['idempotentHint']) is not bool:
                raise ValueError
            if hints['readOnlyHint'] != (name in READ_ONLY_DESCRIPTORS):
                raise ValueError
            if hints['readOnlyHint'] and hints['destructiveHint']:
                raise ValueError
            if any(hints.get(key) is not expected for key, expected in
                   reviewed_effects(name, full_control=full_control).items()):
                raise ValueError
            for key in ('inputSchema', 'outputSchema'):
                schema = tool[key]
                if not isinstance(schema, dict):
                    raise ValueError
                Draft202012Validator.check_schema(schema)
            inputs = tool['inputSchema']
            properties = inputs.get('properties')
            required = inputs.get('required', [])
            if (inputs.get('type') != 'object' or not isinstance(properties, dict)
                    or inputs.get('additionalProperties') is not False
                    or not set(required) <= properties.keys()):
                raise ValueError
    except (ValueError, TypeError, KeyError, AttributeError, SchemaError):
        # Do not include descriptor contents or third-party exception payloads.
        raise ValueError('CATALOG_CONTRACT_INVALID') from None


def catalog_revision(catalog):
    # Fingerprint the complete published descriptor, including descriptions and
    # future protocol metadata. A schema-only hash misses client-visible drift.
    contract = [catalog[name] for name in sorted(catalog)]
    return hashlib.sha256(json.dumps(contract, sort_keys=True, ensure_ascii=False,
                                     separators=(',', ':')).encode('utf-8')).hexdigest()


def definition(name, description, properties, required, output, *, readonly=False):
    return {"name": name, "description": description,
            "inputSchema": {"type": "object", "properties": properties, "required": required,
                            "additionalProperties": False},
            "outputSchema": output,
            "annotations": {"readOnlyHint": readonly, "destructiveHint": not readonly,
                            "idempotentHint": False, "openWorldHint": False}}


def unified_catalog(bf_server, *, full_control=False, search_sessions=4):
    tools = {name: deepcopy(tool_definition(name)) for name in TOOL_REGISTRY}
    for tool in asyncio.run(bf_server.list_tools()):
        if tool.name in {"task_context", "task_diagnostics"}:
            continue
        schema = deepcopy(tool.parameters)
        schema["properties"].pop("bf_task_id", None)
        schema["required"] = [p for p in schema.get("required", []) if p != "bf_task_id"]
        tools[tool.name] = {"name": tool.name,
            "description": (tool.description or "").replace("bf_task_id", "workflow_id"),
            "inputSchema": schema, "outputSchema": deepcopy(tool.output_schema),
            "annotations": tool.annotations.model_dump(by_alias=True, exclude_none=True)}
    for name, tool in tools.items():
        upstream_output = tool['outputSchema']
        # All current upstream output schemas are inline. Keep their successful
        # result and native error branches unchanged alongside our own errors.
        tool['outputSchema'] = {'type': 'object', 'anyOf': [
            upstream_output, deepcopy(HOST_ERROR_OUTPUT)]}
        tool['annotations'].update(reviewed_effects(name, full_control=full_control))
        if name == "App":
            tool["description"] = "Switch to or resize an existing application. Use LaunchApplication with a registered profile to start an owned application."
            mode = tool["inputSchema"]["properties"]["mode"]
            mode["enum"] = ["switch", "resize"]
            mode.pop("default", None)
            tool["inputSchema"]["required"] = list(dict.fromkeys([*tool["inputSchema"].get("required", []), "mode"]))
        if name == "server_info":
            continue
        schema = tool["inputSchema"]
        schema["properties"]["workflow_id"] = deepcopy(WORKFLOW)
        schema["required"] = list(dict.fromkeys([*schema.get("required", []), "workflow_id"]))
        schema["additionalProperties"] = False
        tool["description"] = "Requires an active UnifiedTask workflow. " + tool["description"]
        if requires_workflow_write(name) and not name.startswith("Browser"):
            schema["properties"]["request_id"] = deepcopy(TEXT)
            schema["required"] = list(dict.fromkeys([*schema["required"], "request_id"]))
            tool["description"] += " Supply a unique request_id for this operation; repeats never replay an unknown outcome."
            if name == "write_stdin":
                tool["description"] += (
                    " Non-empty input can trigger command-side destructive or external effects; "
                    "it is not a read-only output query."
                    " Use command_status for non-consuming state observation and read_output for retained logs."
                    " Each new output poll needs a new request_id, even when chars is empty; "
                    "reuse the same ID only to retry a lost reply to that exact poll.")
    task_output = {"type": "object", "required": ["ok"], "properties": {
        "ok": {"type": "boolean"}, "state": {"type": "string"}, "code": {"type": "string"},
        "workflow_id": WORKFLOW, "project": {"type": "string"}, "access": {"enum": ["read", "write"]},
        "workflow_ref": WORKFLOW_REF, "created": {"type": "number"},
        "credential_generation": {"type": "integer"}, "commands": {"type": "array"},
        "job_processes": {"type": "object"},
        "last_activity": {"type": "number"}, "idle_seconds": {"type": "number"},
        "workflows": {"type": "array", "items": {"type": "object"}},
        "expires": {"type": "number"}, "instructions": {"type": "string"}, "error": {"type": "object"}}}
    task = definition("UnifiedTask",
        "Begin a project workflow, keep its one-time workflow_id, then activate it. End releases owned resources. "
        "Different projects run concurrently. Use the concrete project directory, not a shared parent; "
        "call shared build scripts by absolute path while keeping that project. For simultaneous edits to one "
        "project, use separate working copies. list shows your workflow_refs and project owners without tokens. "
        "release_idle accepts a workflow_ref only after the configured idle period and only when no operation "
        "or owned resource is running. Busy or unknown resources are retained. Idle sessions are also reaped "
        "automatically. A repeated begin never returns the secret again; if its first reply was lost, "
        "wait for reservation expiry and use a new request_id. To explicitly continue the SAME ACTIVE "
        "workflow after losing its token, list first then resume with workflow_ref, credential_generation "
        "as expected_generation and a unique request_id. This replaces the old credential without restarting "
        "owned commands. Never automatically resume another task on PROJECT_BUSY. Retry a lost resume reply "
        "with exactly the same request_id and parameters. status lists retained command handles and "
        "diagnostic-only owned Job PIDs. A command root may have exited while its descendants still run; "
        "commands=0 does not mean idle. If the owner explicitly wants the entire workflow stopped, "
        "resume the SAME workflow when needed, inspect status, then end it. Do not kill arbitrary PIDs "
        "or restart the host to resolve one workflow. Unknown diagnostics do not prove idle.",
        {"action": {"enum": ["begin", "activate", "status", "end", "list", "release_idle", "resume"]},
         "workflow_id": WORKFLOW, "workflow_ref": WORKFLOW_REF,
         "expected_generation": {"type": "integer", "minimum": 0},
         "project_path": {"type": "string", "minLength": 1}, "request_id": TEXT,
         "access": {"enum": ["read", "write"], "default": "write"},
         "ttl": {"type": "integer", "minimum": 1, "maximum": 300, "default": 120}}, ["action"], task_output)
    properties = task["inputSchema"]["properties"]
    task["inputSchema"]["oneOf"] = []
    for actions, required, allowed in (
        (["begin"], ["project_path", "request_id"], {"action", "project_path", "request_id", "access", "ttl"}),
        (["activate", "status", "end"], ["workflow_id"], {"action", "workflow_id"}),
        (["list"], [], {"action"}),
        (["release_idle"], ["workflow_ref"], {"action", "workflow_ref"}),
        (["resume"], ["workflow_ref", "request_id", "expected_generation"],
         {"action", "workflow_ref", "request_id", "expected_generation"}),
    ):
        # Union-aware clients generate each branch's callable signature without
        # merging the parent properties. Keep every branch self-contained.
        branch = {key: deepcopy(value) for key, value in properties.items() if key in allowed}
        branch["action"] = {"enum": actions}
        task["inputSchema"]["oneOf"].append({"type": "object", "properties": branch,
            "required": ["action", *required], "additionalProperties": False})
    tools["UnifiedTask"] = task
    # Each lifecycle operation has its own reviewed signature. The legacy
    # envelope remains advertised only for existing clients during migration.
    lifecycle = {
        'begin': (
            'Reserve one concrete project workflow. Performs configured expiry/idle maintenance before reserving. '
            'Does not execute a command or activate project resources. The secret credential is returned only once; '
            'a duplicate request_id never returns it again. A lost reply requires reservation expiry before a new reservation.',
            ['project_path', 'request_id'], ['project_path', 'request_id', 'access', 'ttl']),
        'activate': (
            'Activate an owned reserved workflow and initialize its managed runtime resources. '
            'Requires its current secret credential. Refuses expired or inactive reservations; does not execute a project command.',
            ['workflow_id'], ['workflow_id']),
        'resume': (
            'Explicitly rotate the credential of the same owned active workflow, revoking the old credential. '
            'Preserves its commands and resources. Use the current credential_generation from workflow_list as expected_generation. '
            'Retry a lost response only with the identical request_id and parameters; do not take over another task.',
            ['workflow_ref', 'request_id', 'expected_generation'], ['workflow_ref', 'request_id', 'expected_generation']),
        'end': (
            'End the selected owned workflow and release its managed processes, searches and browser resources. '
            'This can stop running work and discard unsaved task-owned state. Requires the current credential. '
            'A cleanup failure is reported and must not be treated as successful release.',
            ['workflow_id'], ['workflow_id']),
        'release_idle': (
            'Release only the specified owned workflow after its configured idle period and with no active or unknown resources. '
            'This ends the workflow and cleans up its resources; it is not a status query. '
            'Recent activity, in-flight calls, active resources or uncertain diagnostics cause refusal.',
            ['workflow_ref'], ['workflow_ref']),
    }
    for name, action in WORKFLOW_ACTIONS.items():
        description, required, fields = lifecycle[action]
        output = deepcopy(task_output)
        output['properties'].pop('workflows')
        if action not in {'begin', 'resume'}:
            output['properties'].pop('workflow_id')
            output['properties'].pop('instructions')
        output['additionalProperties'] = False
        tools[name] = definition(name, description,
            {key: deepcopy(properties[key]) for key in fields}, required, output)
    # Keep the legacy multiplexer for existing clients. These are genuinely
    # read-only entry points, not a readOnly annotation on lifecycle mutations.
    task['description'] += (
        ' Compatibility interface for existing clients. New clients should use workflow_begin, '
        'workflow_activate, workflow_resume, workflow_end, workflow_release_idle, workflow_list '
        'and workflow_status, each with its own explicit signature.')
    metadata = deepcopy(task_output)
    for key in ('workflow_id', 'instructions', 'workflows'):
        metadata['properties'].pop(key)
    metadata['additionalProperties'] = False
    listing = {'type': 'object', 'required': ['ok'], 'additionalProperties': False,
               'properties': {'ok': {'type': 'boolean'},
                              'workflows': {'type': 'array', 'items': deepcopy(metadata)},
                              'error': {'type': 'object'}}}
    tools['workflow_list'] = definition('workflow_list',
        'Read this authenticated owner\'s non-ended workflow metadata without a workflow token. '
        'Does not create, activate, renew, rotate credentials, clean up or end workflows. '
        'Returns references and credential generations, never workflow secrets.',
        {}, [], listing, readonly=True)
    tools['workflow_status'] = definition('workflow_status',
        'Read one owned workflow and its command/resource diagnostics using its current credential. '
        'Does not renew its idle lease, activate it, rotate credentials or release resources. '
        'Reserved and ended workflows are observable; command/job diagnostics apply to active ones. '
        'Unknown job diagnostics do not prove idle. Diagnostic PIDs do not authorize termination.',
        {'workflow_id': deepcopy(WORKFLOW)}, ['workflow_id'], metadata, readonly=True)
    for name in ('workflow_list', 'workflow_status'):
        tools[name]['annotations']['idempotentHint'] = True
    tools['command_status'] = definition('command_status',
        'Observe a retained command handle in this active owned workflow. Does not run commands, '
        'write stdin, consume output, cancel work, renew the idle lease or create a receipt. '
        'Returns the observed root exit code and output references; ok means observation succeeded, '
        'not command/business success. An exited root does not prove its descendants stopped. '
        'Unavailable or missing handles do not prove a command never ran; do not resubmit it. '
        'Use read_output with explicit offsets to inspect retained logs.',
        {'workflow_id': deepcopy(WORKFLOW), 'command_id': deepcopy(TEXT)},
        ['workflow_id', 'command_id'],
        {'type': 'object', 'required': ['ok'], 'additionalProperties': False, 'properties': {
            'ok': {'type': 'boolean'}, 'command_id': deepcopy(TEXT),
            'observation': {'enum': ['available', 'unavailable']},
            'status': {'enum': ['running', 'exited', 'unknown']},
            'exit_code': {'type': ['integer', 'null']}, 'started_at': {'type': 'number'},
            'completed_at': {'type': ['number', 'null']}, 'output_complete': {'type': 'boolean'},
            'stdout_ref': {'type': 'string'}, 'stderr_ref': {'type': 'string'},
            'error': {'type': 'object'}}}, readonly=True)
    tools['command_status']['annotations']['idempotentHint'] = True
    tools['OperationStatus'] = definition('OperationStatus',
        'Query a previously submitted request_id in this workflow without repeating its side effects. '
        'running means only the client wait ended; poll this tool. unknown must be observed, never replayed. '
        'Completed results have bounded retention; an expired result still prevents replay. '
        'Browser actions retain their existing BrowserActionStatus query.',
        {'workflow_id': WORKFLOW, 'request_id': TEXT}, ['workflow_id', 'request_id'],
        {'type': 'object', 'required': ['ok'], 'properties': {
            'ok': {'type': 'boolean'}, 'state': {'enum': ['running', 'completed', 'failed', 'unknown']},
            'request_id': TEXT, 'operation': {'type': 'string'}, 'updated': {'type': 'number'},
            'result': {}, 'result_ref': {'type': ['string', 'null']},
            'result_expired': {'type': 'boolean'}, 'error': {'type': 'object'}}}, readonly=True)
    search_output = {"type": "object", "required": ["ok"], "properties": {
        "ok": {"type": "boolean"}, "search_id": {"type": "string"}, "state": {"type": "string"},
        "reason": {"type": ["string", "null"]}, "next_cursor": {"type": "integer"},
        "has_more": {"type": "boolean"}, "results": {"type": "array", "items": {"type": "object",
            "properties": {"path": {"type": "string"}, "line": {"type": "integer"}, "text": {"type": "string"}},
            "required": ["path", "line", "text"]}}, "error": {"type": "object"}}}
    search = definition("SearchSession", "Start/read/status/stop/release a bounded progressive search in this workflow's project. "
        f"Use nonnegative absolute cursors. At most 2 retained sessions per workflow and {search_sessions} per host. "
        "stop retains results; release stops and forgets one search, freeing its slot without ending the workflow.",
        {"action": {"enum": ["start", "read", "status", "stop", "release"]}, "workflow_id": WORKFLOW,
         "pattern": {"type": "string", "minLength": 1, "maxLength": 1024}, "regex": {"type": "boolean"},
         "search_id": TEXT, "cursor": {"type": "integer", "minimum": 0},
         "limit": {"type": "integer", "minimum": 1, "maximum": 1000}}, ["action", "workflow_id"], search_output)
    search["inputSchema"]["allOf"] = [{"if": {"properties": {"action": {"const": "start"}}},
        "then": {"required": ["pattern"]}, "else": {"required": ["search_id"]}}]
    tools["SearchSession"] = search
    apply_tool_presentation(tools, full_control=full_control)
    validate_catalog_contract(tools, full_control=full_control)
    return tools
